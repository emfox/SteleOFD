#!/usr/bin/env python3
"""Conformance gate for the GB/T 33190-2016 register.

Checks that every verified clause links to a real test, that no
`gb_t_33190_*` test is orphaned, and regenerates docs/COMPLIANCE.md.

The register stores bare test names; cargo reports them qualified by module,
so both sides are compared on the last path segment.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
REGISTER = REPO / "compliance" / "gb-t-33190.toml"
MATRIX = REPO / "docs" / "COMPLIANCE.md"
PREFIX = "gb_t_33190_"
KNOWN_STATUS = ("verified", "partial", "untested", "deviation")
NEEDS_TESTS = ("verified", "partial")


def bare(name: str) -> str:
    """Drop the module path cargo prefixes test names with."""
    return name.rsplit("::", 1)[-1]


def collect_tests(explicit: Path | None) -> set[str]:
    """Bare test names, either from a file or by asking cargo."""
    if explicit is not None:
        return {line.strip() for line in explicit.read_text(encoding="utf-8").splitlines() if line.strip()}
    proc = subprocess.run(
        ["cargo", "test", "--workspace", "--no-fail-fast", "--", "--list"],
        cwd=REPO,
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        print(proc.stdout[-2000:])
        print(proc.stderr[-2000:])
        raise SystemExit("cargo test --list failed; cannot collect test names")
    names = set()
    for line in proc.stdout.splitlines():
        line = line.strip()
        if line.endswith(": test") and not line.startswith("Running"):
            names.add(bare(line[: -len(": test")].strip()))
    return names


def load_register() -> dict:
    with REGISTER.open("rb") as handle:
        return tomllib.load(handle)


def validate(data: dict, tests: set[str]) -> tuple[list[str], dict[str, int]]:
    errors: list[str] = []
    counts = {status: 0 for status in KNOWN_STATUS}
    seen: set[str] = set()
    linked: set[str] = set()

    for item in data.get("item", []):
        clause = item.get("clause", "<missing>")
        status = item.get("status", "<missing>")
        if status not in KNOWN_STATUS:
            errors.append(f"{clause}: unknown status {status!r}")
            continue
        if clause in seen:
            errors.append(f"{clause}: duplicate clause entry")
        seen.add(clause)
        counts[status] += 1

        names = item.get("tests", [])
        for name in names:
            linked.add(name)
            if name not in tests:
                errors.append(f"{clause}: test {name!r} does not exist")
            if not name.startswith(PREFIX):
                errors.append(f"{clause}: test {name!r} misses the {PREFIX} prefix")
        if status in NEEDS_TESTS and not names:
            errors.append(f"{clause}: status {status} needs at least one linked test")

    for name in sorted(tests):
        if name.startswith(PREFIX) and name not in linked:
            errors.append(f"orphan test {name!r} is not registered under any clause")
    return errors, counts


def render(data: dict, counts: dict[str, int], tests: set[str]) -> str:
    total = sum(counts.values())
    covered = counts["verified"] + counts["partial"]
    ratio = covered / total if total else 0.0
    lines = [
        "# GB/T 33190-2016 conformance",
        "",
        "Generated by `scripts/check_compliance.py`; edit `compliance/gb-t-33190.toml`.",
        "",
        f"- Standard: {data.get('standard', '?')} - {data.get('title', '?')}",
        f"- Clauses registered: {total}",
        f"- Covered by tests: {covered} ({ratio:.0%})",
        "",
        "| Clause | Title | Status | Tests |",
        "| --- | --- | --- | --- |",
    ]
    for item in data.get("item", []):
        names = ", ".join(f"`{n}`" for n in item.get("tests", [])) or "-"
        note = item.get("note")
        suffix = f" ({note})" if note else ""
        lines.append(
            f"| {item['clause']} | {item['title']}{suffix} | {item['status']} | {names} |"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--tests-file", type=Path, help="skip cargo and read this list")
    parser.add_argument("--check-only", action="store_true", help="do not rewrite the matrix")
    args = parser.parse_args()

    if not REGISTER.exists():
        print(f"missing register: {REGISTER}")
        return 1
    tests = collect_tests(args.tests_file)
    data = load_register()
    errors, counts = validate(data, tests)

    if not args.check_only:
        MATRIX.write_text(render(data, counts, tests), encoding="utf-8")

    total = sum(counts.values())
    covered = counts["verified"] + counts["partial"]
    print(f"clauses: {total}, covered: {covered}, tests seen: {len(tests)}")
    if errors:
        print(f"FAILED: {len(errors)} violation(s)")
        for error in errors:
            print(f"  {error}")
        return 1
    print("OK: conformance register is consistent")
    return 0


if __name__ == "__main__":
    sys.exit(main())
